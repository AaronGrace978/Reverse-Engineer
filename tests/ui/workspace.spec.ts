import { expect, test } from '@playwright/test'

test('workbench, preview guard, providers, and persistent notebook', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Make the unknown understandable.' })).toBeVisible()
  await expect(page.locator('.topbar-status')).toContainText('BROWSER PREVIEW')
  await page.getByRole('button', { name: /Mathematics Problems/ }).click()
  await page.getByRole('button', { name: /Build a rigorous solution/ }).click()
  await expect(page.getByRole('textbox', { name: 'Your research question' })).toHaveValue(/Solve x²/)
  await page.getByRole('button', { name: 'Send research question' }).click()
  await expect(page.getByRole('alert')).toContainText('browser preview')
  await page.getByRole('button', { name: 'Dismiss error' }).click()
  await page.getByRole('button', { name: /Model providers/ }).click()
  await expect(page.getByRole('dialog', { name: 'Model providers' })).toBeVisible()
  await page.getByRole('navigation', { name: 'Provider settings' }).getByRole('button', { name: /Ollama Cloud/ }).click()
  await expect(page.getByLabel('API key', { exact: false })).toBeDisabled()
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: /Knowledge notebook/ }).click()
  await page.getByRole('button', { name: 'Add a lesson', exact: true }).click()
  const lessonInput = page.getByLabel('What should the notebook remember?')
  await lessonInput.pressSequentially('Check dimensions and units before inferring a mechanism.')
  await expect(lessonInput).toBeFocused()
  await page.getByRole('button', { name: 'Save lesson', exact: true }).click()
  await expect(page.getByText('Check dimensions and units before inferring a mechanism.', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /Knowledge notebook/ }).click()
  await expect(page.getByText('Check dimensions and units before inferring a mechanism.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Evaluation harness', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Evaluation harness', exact: true })).toBeVisible()
  await expect(page.getByText('A smoke test, not a capability score')).toBeVisible()
  expect(errors).toEqual([])
})

test('investigation creation, rename, delete, and layout', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /New investigation/ }).click()
  await page.getByRole('button', { name: 'Untitled investigation', exact: true }).click()
  await page.getByRole('textbox', { name: 'Investigation name' }).fill('Gear train analysis')
  await page.getByRole('button', { name: 'Save name' }).click()
  await expect(page.getByRole('heading', { name: 'Gear train analysis' })).toBeVisible()
  const dimensions = await page.evaluate(() => ({ width: document.documentElement.scrollWidth, viewport: innerWidth }))
  expect(dimensions.width).toBe(dimensions.viewport)
  await page.getByRole('button', { name: 'Delete investigation', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete investigation', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'A space for your next discovery' })).toBeVisible()
  await page.screenshot({ path: 'test-results/workbench.png', fullPage: true })
})
